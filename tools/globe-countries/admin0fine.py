#!/usr/bin/env python3
"""Regenerate internal/web/static/app/globe-admin0fine/00-admin0fine.js (ADR 0090).

A lazily loaded, higher-resolution world land/coastline tier for close zoom outside
Indonesia. Source: Natural Earth 1:10m admin-0 countries (public domain,
https://www.naturalearthdata.com), pinned upstream commit
ca96624a56bd078437bca8184e78163e5039ad19. Standard library only.

The coarse 1:50m map (tools/globe-countries/gen.py, TOL 0.06 deg, Q 20) is crisp only
to ~zoom 12 on a DPR-2 screen. This tier keeps Douglas-Peucker TOL 0.001 deg (~110 m)
and snaps to 1/1000 deg, so the coastline error is <= ~1.5 CSS px up to the globe's
maximum zoom. Rings are delta zigzag varints, 5 payload bits per character; each row
is [iso, [ring,...]]. Like admin1/admin2 it is imported only when the view needs it,
so the initial globe bundle does not grow.

Usage:
    python3 tools/globe-countries/admin0fine.py <ne10m-countries.geojson> <dst>
    python3 tools/globe-countries/admin0fine.py --fetch <dst>
"""
import json
import os
import shutil
import sys
import tempfile
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen import douglas_peucker, varint  # noqa: E402

PIN = "ca96624a56bd078437bca8184e78163e5039ad19"
URL = ("https://raw.githubusercontent.com/nvkelso/natural-earth-vector/%s/"
       "geojson/ne_10m_admin_0_countries.geojson" % PIN)
TOL = 0.001     # Douglas-Peucker tolerance, degrees on the sphere (~110 m)
Q = 1000        # coordinate units per degree
MIN_PTS = 3
UA = {"User-Agent": "pantau-geodata-generator"}


def encode_ring(ring):
    pts = ring[:-1] if ring[0] == ring[-1] else list(ring)
    if len(pts) < MIN_PTS:
        return None
    out, px, py = "", 0, 0
    for x, y in douglas_peucker(pts, TOL):
        xi, yi = round(x * Q), round(y * Q)
        if out and xi == px and yi == py:
            continue
        out += varint(xi - px) + varint(yi - py)
        px, py = xi, yi
    return out if len(out) else None


def main(src, dst):
    with open(src, encoding="utf-8") as f:
        features = json.load(f)["features"]
    rows = []
    for feat in features:
        geom = feat["geometry"]
        if not geom:
            continue
        polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
        rings = []
        for poly in polys:
            for ring in poly:
                enc = encode_ring(ring)
                if enc:
                    rings.append(enc)
        if not rings:
            continue
        props = feat["properties"]
        iso = props.get("ISO_A2_EH") or props.get("ISO_A2") or ""
        if iso in ("-99", "-1"):
            iso = ""
        rows.append([iso, rings])
    with open(dst, "w", encoding="utf-8") as out:
        out.write(
            "/* Embedded Natural Earth 1:10m land/coastline detail for the Globe Radar (ADR 0090).\n"
            " * Generated by tools/globe-countries/admin0fine.py from Natural Earth 1:10m admin-0\n"
            " * (public domain), pinned at %s; do not edit by hand.\n"
            " * rows = [iso, [ring,...]]; rings are '.'-separated delta zigzag varints of (lon,lat)\n"
            " * in 1/q degree, decoded by 02-globe-geo.js. Air-gapped: no CDN (ADR 0013). */\n"
            "window.GLOBE_ADMIN0FINE = { q: %d, c: [\n" % (PIN, Q)
        )
        for iso, rings in rows:
            out.write(" [%s, %s],\n" % (
                json.dumps(iso), json.dumps(".".join(rings), separators=(",", ":"))))
        out.write("] };\n")
    print("%d countries, %d chars" % (len(rows), sum(len("".join(r)) for _, r in rows)), file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] != "--fetch":
        main(sys.argv[1], sys.argv[2])
    elif len(sys.argv) == 3 and sys.argv[1] == "--fetch":
        tmp = tempfile.mkdtemp(prefix="globe-admin0fine-")
        try:
            path = os.path.join(tmp, "ne10m.geojson")
            req = urllib.request.Request(URL, headers=UA)
            with open(path, "wb") as f:
                f.write(urllib.request.urlopen(req, timeout=120).read())
            main(path, sys.argv[2])
        finally:
            shutil.rmtree(tmp)
    else:
        sys.exit(__doc__)
